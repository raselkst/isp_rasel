"use client";

import { useState, useMemo } from "react";
import { DashboardSidebar } from "@/components/dashboard/dashboard-sidebar";
import { DashboardTopbar } from "@/components/dashboard/dashboard-topbar";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import {
  Download, Search, ArrowUpDown, ChevronLeft, ChevronRight,
  AlertCircle, CheckCircle2, XCircle, TrendingUp,
  Filter, RefreshCw, CalendarDays, CreditCard, CalendarRange, X
} from "lucide-react";
import { cn } from "@/lib/utils";

const columns = [
  { key: "date", label: "Date" },
  { key: "total", label: "Total Cards" },
  { key: "valid", label: "Valid" },
  { key: "invalid", label: "Invalid" },
  { key: "generatedBy", label: "Generated By" },
];

const datePresets = [
  { id: "today", label: "Today" },
  { id: "yesterday", label: "Yesterday" },
  { id: "7days", label: "Last 7 Days" },
  { id: "30days", label: "Last 30 Days" },
  { id: "month", label: "This Month" },
  { id: "custom", label: "Custom" },
];

function seededRandom(seed: number) {
  const x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

function generateReports() {
  const reports = [];
  const baseYear = 2025;
  const baseMonth = 8;

  for (let i = 0; i < 30; i++) {
    const seed1 = i * 13 + 7;
    const seed2 = i * 17 + 3;

    const total = Math.floor(50 + seededRandom(seed1) * 300);
    const invalid = Math.floor(seededRandom(seed2) * 30);
    const day = 30 - i;
    const date = `${baseYear}-${String(baseMonth + 1).padStart(2, "0")}-${String(day).padStart(2, "0")}`;

    reports.push({
      id: i + 1,
      date,
      total,
      valid: total - invalid,
      invalid,
      generatedBy: ["Admin", "Reseller-A", "Reseller-B", "NSP"][i % 4],
    });
  }
  return reports;
}

const allReports = generateReports();
const FIXED_TODAY = "2025-09-30";
const FIXED_7DAYS_AGO = "2025-09-23";

export default function CardReportByDatePage() {
  const [reports] = useState(allReports);
  const [activePreset, setActivePreset] = useState("7days");
  const [dateFrom, setDateFrom] = useState(FIXED_7DAYS_AGO);
  const [dateTo, setDateTo] = useState(FIXED_TODAY);
  const [searchTerm, setSearchTerm] = useState("");
  const [rowsPerPage, setRowsPerPage] = useState(10);
  const [currentPage, setCurrentPage] = useState(1);
  const [sortKey, setSortKey] = useState<string | null>("date");
  const [sortOrder, setSortOrder] = useState<"asc" | "desc">("desc");
  const [isLoading, setIsLoading] = useState(false);

  const handlePreset = (presetId: string) => {
    setActivePreset(presetId);
    switch (presetId) {
      case "today":
        setDateFrom(FIXED_TODAY);
        setDateTo(FIXED_TODAY);
        break;
      case "yesterday":
        setDateFrom("2025-09-29");
        setDateTo("2025-09-29");
        break;
      case "7days":
        setDateFrom(FIXED_7DAYS_AGO);
        setDateTo(FIXED_TODAY);
        break;
      case "30days":
        setDateFrom("2025-09-01");
        setDateTo(FIXED_TODAY);
        break;
      case "month":
        setDateFrom("2025-09-01");
        setDateTo(FIXED_TODAY);
        break;
      case "custom":
        return;
    }
    setCurrentPage(1);
  };

  const filteredReports = useMemo(() => {
    return reports.filter((r) => {
      const matchesDate = r.date >= dateFrom && r.date <= dateTo;
      const matchesSearch =
        !searchTerm ||
        r.date.includes(searchTerm) ||
        r.generatedBy.toLowerCase().includes(searchTerm.toLowerCase());
      return matchesDate && matchesSearch;
    });
  }, [reports, dateFrom, dateTo, searchTerm]);

  const sortedReports = useMemo(() => {
    if (!sortKey) return filteredReports;
    return [...filteredReports].sort((a: any, b: any) => {
      const aVal = a[sortKey];
      const bVal = b[sortKey];
      if (aVal < bVal) return sortOrder === "asc" ? -1 : 1;
      if (aVal > bVal) return sortOrder === "asc" ? 1 : -1;
      return 0;
    });
  }, [filteredReports, sortKey, sortOrder]);

  const stats = useMemo(() => {
    const total = filteredReports.reduce((sum, r) => sum + r.total, 0);
    const valid = filteredReports.reduce((sum, r) => sum + r.valid, 0);
    const invalid = filteredReports.reduce((sum, r) => sum + r.invalid, 0);
    const rate = total > 0 ? ((valid / total) * 100).toFixed(1) : "0.0";
    return { total, valid, invalid, rate };
  }, [filteredReports]);

  const totalPages = Math.ceil(sortedReports.length / rowsPerPage) || 1;
  const startIndex = (currentPage - 1) * rowsPerPage;
  const paginatedReports = sortedReports.slice(startIndex, startIndex + rowsPerPage);

  const handleSort = (key: string) => {
    if (sortKey === key) {
      setSortOrder(sortOrder === "asc" ? "desc" : "asc");
    } else {
      setSortKey(key);
      setSortOrder("asc");
    }
  };

  const handleExport = () => {
    const headers = [...columns.map((c) => c.label), "Validity Rate"].join(",");
    const csvRows = sortedReports.map((r) => {
      const rate = ((r.valid / r.total) * 100).toFixed(1);
      return [...columns.map((col) => `"${(r as any)[col.key]}"`), `"${rate}%"`].join(",");
    });
    const csv = [headers, ...csvRows].join("\n");
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `card-report-${dateFrom}-to-${dateTo}.csv`;
    link.click();
    URL.revokeObjectURL(url);
    alert(`Exported ${sortedReports.length} report(s).`);
  };

  const handleRefresh = () => {
    setIsLoading(true);
    setTimeout(() => {
      setIsLoading(false);
      alert("Report refreshed successfully!");
    }, 600);
  };

  const handleApplyFilter = () => {
    setIsLoading(true);
    setTimeout(() => {
      setIsLoading(false);
      setCurrentPage(1);
    }, 600);
  };

  const handleResetFilters = () => {
    setSearchTerm("");
    setDateFrom(FIXED_7DAYS_AGO);
    setDateTo(FIXED_TODAY);
    setActivePreset("7days");
    setCurrentPage(1);
    setSortKey("date");
    setSortOrder("desc");
    alert("Filters reset!");
  };

  const getValidityRate = (valid: number, total: number) => {
    return total > 0 ? (valid / total) * 100 : 0;
  };

  const getValidityLabel = (rate: number) => {
    if (rate >= 95) return { label: "Excellent", color: "text-success", bg: "bg-success-tint" };
    if (rate >= 85) return { label: "Good", color: "text-warning", bg: "bg-warning-tint" };
    return { label: "Poor", color: "text-destructive", bg: "bg-destructive/10" };
  };

  const formatDate = (dateStr: string) => {
    const [year, month, day] = dateStr.split("-");
    const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    return `${day} ${months[parseInt(month) - 1]} ${year}`;
  };

  const hasActiveFilters =
    searchTerm ||
    dateFrom !== FIXED_7DAYS_AGO ||
    dateTo !== FIXED_TODAY ||
    activePreset !== "7days";

  return (
    <div className="flex min-h-screen bg-slate-50">
      <DashboardSidebar />

      <div className="flex-1 min-w-0">
        <DashboardTopbar />

        <div className="px-4 sm:px-8 py-7">
          {/* Header */}
          <div className="flex flex-wrap items-center justify-between gap-4 mb-6">
            <h1 className="font-heading text-[26px] font-bold tracking-tight text-signal">
              Card Report · Date Wise
            </h1>
            <div className="flex items-center gap-2">
              <Button
                variant="outline"
                onClick={handleRefresh}
                disabled={isLoading}
                className="rounded-full gap-1.5 font-semibold text-signal border-signal/30 hover:bg-signal/5"
              >
                <RefreshCw className={cn("h-4 w-4", isLoading && "animate-spin")} /> Refresh
              </Button>
              <Button
                onClick={handleExport}
                className="rounded-full gap-1.5 font-semibold bg-signal hover:bg-signal-hover text-white border-0 shadow-md"
              >
                <Download className="h-4 w-4" /> Export CSV
              </Button>
            </div>
          </div>

          {/* Date Presets */}
          <div className="flex flex-wrap items-center gap-2 mb-5">
            <span className="text-xs font-semibold text-slate-500 uppercase flex items-center gap-1 mr-2">
              <CalendarRange className="w-3.5 h-3.5" /> Quick Range:
            </span>
            {datePresets.map((p) => (
              <button
                key={p.id}
                type="button"
                onClick={() => handlePreset(p.id)}
                className={cn(
                  "px-4 py-1.5 rounded-full text-xs font-semibold border transition-all",
                  activePreset === p.id
                    ? "bg-signal text-white border-signal shadow-md"
                    : "bg-white text-slate-500 border-slate-200 hover:border-signal/50 hover:text-signal"
                )}
              >
                {p.label}
              </button>
            ))}
          </div>

          {/* Filter Panel */}
          <div className="bg-white rounded-2xl border border-slate-200 p-5 mb-5 flex flex-wrap items-end gap-4 shadow-sm">
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-500 uppercase flex items-center gap-1">
                <CalendarDays className="w-3 h-3" /> Date From
              </label>
              <Input
                type="date"
                value={dateFrom}
                onChange={(e) => { setDateFrom(e.target.value); setActivePreset("custom"); }}
                className="rounded-xl w-48 border-slate-200 text-signal"
              />
            </div>

            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-500 uppercase flex items-center gap-1">
                <CalendarDays className="w-3 h-3" /> Date To
              </label>
              <Input
                type="date"
                value={dateTo}
                onChange={(e) => { setDateTo(e.target.value); setActivePreset("custom"); }}
                className="rounded-xl w-48 border-slate-200 text-signal"
              />
            </div>

            <div className="flex-1 min-w-[200px] space-y-1.5">
              <label className="text-xs font-semibold text-slate-500 uppercase flex items-center gap-1">
                <Search className="w-3 h-3" /> Search
              </label>
              <Input
                value={searchTerm}
                onChange={(e) => { setSearchTerm(e.target.value); setCurrentPage(1); }}
                placeholder="Search by date or generated by..."
                className="rounded-xl border-slate-200 text-signal"
              />
            </div>

            <Button
              onClick={handleApplyFilter}
              className="rounded-xl font-semibold h-10 px-6 bg-signal hover:bg-signal-hover text-white border-0 shadow-md"
            >
              <Filter className="h-4 w-4 mr-2" /> Apply Filter
            </Button>

            {hasActiveFilters && (
              <Button
                onClick={handleResetFilters}
                variant="outline"
                className="rounded-xl font-semibold h-10 px-6 text-destructive border-destructive/30 hover:bg-destructive/5"
              >
                <X className="h-4 w-4 mr-2" /> Reset
              </Button>
            )}
          </div>

          {/* 🎯 Semantic Compact Stat Cards - এক লাইনে */}
          <div className="grid grid-cols-2 lg:grid-cols-4 gap-3 mb-6">
            {/* Total - Theme Primary */}
            <div className="relative overflow-hidden rounded-xl p-3 flex items-center gap-3 bg-gradient-to-br from-signal to-signal-light text-white shadow-md">
              <div className="w-9 h-9 rounded-lg bg-white/25 backdrop-blur-sm flex items-center justify-center shrink-0">
                <CreditCard className="w-4 h-4" />
              </div>
              <div className="flex items-baseline gap-2 min-w-0 flex-1">
                <p className="text-[11px] font-semibold uppercase opacity-90 whitespace-nowrap">Total</p>
                <p className="text-lg font-heading font-bold">{stats.total.toLocaleString()}</p>
              </div>
              <div className="absolute -right-3 -bottom-3 w-16 h-16 rounded-full border-2 border-white/10" />
            </div>

            {/* Valid - Success */}
            <div className="relative overflow-hidden rounded-xl p-3 flex items-center gap-3 bg-gradient-to-br from-success to-success/80 text-white shadow-md">
              <div className="w-9 h-9 rounded-lg bg-white/25 backdrop-blur-sm flex items-center justify-center shrink-0">
                <CheckCircle2 className="w-4 h-4" />
              </div>
              <div className="flex items-baseline gap-2 min-w-0 flex-1">
                <p className="text-[11px] font-semibold uppercase opacity-90 whitespace-nowrap">Valid</p>
                <p className="text-lg font-heading font-bold">{stats.valid.toLocaleString()}</p>
              </div>
              <div className="absolute -right-3 -bottom-3 w-16 h-16 rounded-full border-2 border-white/10" />
            </div>

            {/* Invalid - Destructive */}
            <div className="relative overflow-hidden rounded-xl p-3 flex items-center gap-3 bg-gradient-to-br from-destructive to-destructive/80 text-white shadow-md">
              <div className="w-9 h-9 rounded-lg bg-white/25 backdrop-blur-sm flex items-center justify-center shrink-0">
                <XCircle className="w-4 h-4" />
              </div>
              <div className="flex items-baseline gap-2 min-w-0 flex-1">
                <p className="text-[11px] font-semibold uppercase opacity-90 whitespace-nowrap">Invalid</p>
                <p className="text-lg font-heading font-bold">{stats.invalid.toLocaleString()}</p>
              </div>
              <div className="absolute -right-3 -bottom-3 w-16 h-16 rounded-full border-2 border-white/10" />
            </div>

            {/* Rate - Violet Accent */}
            <div className="relative overflow-hidden rounded-xl p-3 flex items-center gap-3 bg-gradient-to-br from-violet-accent to-violet-accent/80 text-white shadow-md">
              <div className="w-9 h-9 rounded-lg bg-white/25 backdrop-blur-sm flex items-center justify-center shrink-0">
                <TrendingUp className="w-4 h-4" />
              </div>
              <div className="flex items-baseline gap-2 min-w-0 flex-1">
                <p className="text-[11px] font-semibold uppercase opacity-90 whitespace-nowrap">Rate</p>
                <p className="text-lg font-heading font-bold">{stats.rate}%</p>
              </div>
              <div className="w-12 h-1.5 rounded-full bg-white/25 overflow-hidden shrink-0">
                <div
                  className="h-full bg-white transition-all duration-500"
                  style={{ width: `${stats.rate}%` }}
                />
              </div>
              <div className="absolute -right-3 -bottom-3 w-16 h-16 rounded-full border-2 border-white/10" />
            </div>
          </div>

          {/* Table Card */}
          <div className="bg-white rounded-2xl border border-slate-200 overflow-hidden shadow-sm">
            <div className="flex flex-wrap items-center justify-between gap-4 p-4 border-b border-slate-100">
              <div className="flex items-center gap-2 text-sm text-slate-500">
                <span>Show</span>
                <select
                  value={rowsPerPage}
                  onChange={(e) => { setRowsPerPage(Number(e.target.value)); setCurrentPage(1); }}
                  className="border border-slate-200 rounded-lg px-2 py-1 bg-white text-sm text-signal"
                >
                  <option value={10}>10</option>
                  <option value={25}>25</option>
                  <option value={50}>50</option>
                  <option value={100}>100</option>
                </select>
                <span>entries</span>
              </div>
              <div className="text-sm text-slate-500">
                Found <span className="font-semibold text-signal">{sortedReports.length}</span> day(s)
              </div>
            </div>

            <div className="overflow-x-auto">
              <table className="w-full text-sm min-w-[900px]">
                <thead>
                  <tr className="bg-signal text-white">
                    <th className="text-left px-6 py-4 font-semibold text-xs whitespace-nowrap w-16">#</th>
                    {columns.map((c) => (
                      <th
                        key={c.key}
                        onClick={() => handleSort(c.key)}
                        className={cn(
                          "text-left px-6 py-4 font-semibold text-xs whitespace-nowrap cursor-pointer transition-colors select-none",
                          sortKey === c.key ? "bg-white/10" : "hover:bg-white/10"
                        )}
                      >
                        <div className="flex items-center gap-1">
                          {c.label}
                          <ArrowUpDown className={cn("w-3 h-3", sortKey === c.key ? "opacity-100" : "opacity-60")} />
                        </div>
                      </th>
                    ))}
                    <th className="text-left px-6 py-4 font-semibold text-xs whitespace-nowrap">
                      Validity Rate
                    </th>
                  </tr>
                </thead>
                <tbody>
                  {isLoading ? (
                    <tr>
                      <td colSpan={columns.length + 2} className="px-6 py-16 text-center">
                        <div className="flex flex-col items-center gap-3">
                          <RefreshCw className="w-8 h-8 text-signal animate-spin" />
                          <p className="text-sm text-slate-500">Loading report...</p>
                        </div>
                      </td>
                    </tr>
                  ) : paginatedReports.length > 0 ? (
                    paginatedReports.map((r, index) => {
                      const rate = getValidityRate(r.valid, r.total);
                      const validityLabel = getValidityLabel(rate);
                      return (
                        <tr
                          key={r.id}
                          className="border-t border-slate-100 hover:bg-slate-50 transition-colors"
                        >
                          <td className="px-6 py-4 font-medium text-slate-500">
                            {startIndex + index + 1}
                          </td>
                          <td className="px-6 py-4">
                            <div className="flex items-center gap-2">
                              <div className="w-8 h-8 rounded-lg bg-signal-tint flex items-center justify-center">
                                <CalendarDays className="w-4 h-4 text-signal" />
                              </div>
                              <span className="font-semibold text-signal">{formatDate(r.date)}</span>
                            </div>
                          </td>
                          <td className="px-6 py-4 font-semibold text-signal">{r.total.toLocaleString()}</td>
                          <td className="px-6 py-4">
                            <span className="inline-flex items-center gap-1.5 text-success font-semibold">
                              <CheckCircle2 className="w-3.5 h-3.5" />
                              {r.valid.toLocaleString()}
                            </span>
                          </td>
                          <td className="px-6 py-4">
                            <span className="inline-flex items-center gap-1.5 text-destructive font-semibold">
                              <XCircle className="w-3.5 h-3.5" />
                              {r.invalid.toLocaleString()}
                            </span>
                          </td>
                          <td className="px-6 py-4 text-xs">
                            <span className="bg-violet-accent-tint text-violet-accent font-semibold px-2 py-1 rounded-md border border-violet-accent/30">
                              {r.generatedBy}
                            </span>
                          </td>
                          <td className="px-6 py-4 w-52">
                            <div className="space-y-1.5">
                              <div className="flex items-center justify-between">
                                <span className="text-xs font-semibold text-signal">{rate.toFixed(1)}%</span>
                                <span className={cn(
                                  "text-[10px] font-bold px-2 py-0.5 rounded-full",
                                  validityLabel.bg,
                                  validityLabel.color
                                )}>
                                  {validityLabel.label}
                                </span>
                              </div>
                              <div className="w-full h-2 rounded-full bg-slate-100 overflow-hidden">
                                <div
                                  className={cn(
                                    "h-full transition-all duration-500",
                                    rate >= 95 ? "bg-success" : rate >= 85 ? "bg-warning" : "bg-destructive"
                                  )}
                                  style={{ width: `${rate}%` }}
                                />
                              </div>
                            </div>
                          </td>
                        </tr>
                      );
                    })
                  ) : (
                    <tr>
                      <td colSpan={columns.length + 2} className="px-6 py-16 text-center text-slate-500">
                        <AlertCircle className="w-10 h-10 mx-auto mb-3 opacity-40" />
                        <p className="font-semibold text-signal">No report available for selected range</p>
                        <p className="text-xs mt-1">Try changing the date range or filters</p>
                        {hasActiveFilters && (
                          <button
                            onClick={handleResetFilters}
                            className="mt-3 text-xs font-semibold text-signal hover:underline"
                          >
                            Reset Filters
                          </button>
                        )}
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>

            {/* Pagination */}
            <div className="flex flex-wrap items-center justify-between gap-4 px-6 py-4 border-t border-slate-100 text-sm">
              <div className="text-slate-500">
                Showing {sortedReports.length > 0 ? startIndex + 1 : 0} to{" "}
                {Math.min(startIndex + rowsPerPage, sortedReports.length)} of {sortedReports.length} entries
              </div>
              <div className="flex items-center gap-2">
                <Button
                  variant="outline"
                  size="icon"
                  onClick={() => setCurrentPage((p) => Math.max(1, p - 1))}
                  disabled={currentPage === 1}
                  className="rounded-full h-8 w-8 border-slate-200"
                >
                  <ChevronLeft className="w-4 h-4" />
                </Button>
                {Array.from({ length: Math.min(totalPages, 5) }).map((_, i) => {
                  const page = i + 1;
                  return (
                    <Button
                      key={page}
                      variant={currentPage === page ? "default" : "outline"}
                      size="icon"
                      onClick={() => setCurrentPage(page)}
                      className={cn(
                        "rounded-full h-8 w-8 text-xs font-semibold",
                        currentPage === page ? "bg-signal text-white" : "border-slate-200 text-signal"
                      )}
                    >
                      {page}
                    </Button>
                  );
                })}
                {totalPages > 5 && <span className="text-slate-500 px-1">...</span>}
                <Button
                  variant="outline"
                  size="icon"
                  onClick={() => setCurrentPage((p) => Math.min(totalPages, p + 1))}
                  disabled={currentPage === totalPages}
                  className="rounded-full h-8 w-8 border-slate-200"
                >
                  <ChevronRight className="w-4 h-4" />
                </Button>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}