function Field({ label, children, required }: { label: string; children: React.ReactNode; required?: boolean }) {
  return (
    <div className="space-y-2">
      <span className="font-semibold text-sm block text-signal">
        {label} {required && <span className="text-destructive">*</span>}
      </span>
      {children}
    </div>
  );
}

// 🎯 Theme-Connected State Badge
function getStateBadge(state: string) {
  switch (state) {
    case "Active":
      return "bg-success-tint text-success border-success/30";
    case "Used":
      return "bg-signal-tint text-signal border-signal/30";
    case "Expired":
      return "bg-destructive/10 text-destructive border-destructive/30";
    case "Unused":
      return "bg-warning-tint text-warning border-warning/30";
    default:
      return "bg-slate-100 text-slate-600 border-slate-200";
  }
}

export function CardSearchModal({ open, onClose, onSubmit }: CardSearchModalProps) {
  const [searchTerm, setSearchTerm] = useState("");
  const [showAdvanced, setShowAdvanced] = useState(false);
  const [isSearching, setIsSearching] = useState(false);
  const [results, setResults] = useState<typeof mockSearchResults | null>(null);
  const [advancedFilters, setAdvancedFilters] = useState({
    state: "",
    protocol: "",
    package: "",
    dateFrom: "",
    dateTo: "",
  });

  const handleSearch = () => {
    if (!searchTerm.trim() && !showAdvanced) {
      alert("Please enter a Card No or Ref No to search.");
      return;
    }
    setIsSearching(true);
    setResults(null);

    setTimeout(() => {
      const term = searchTerm.toLowerCase();
      let filtered = mockSearchResults.filter(
        (c) =>
          c.cardNo.toLowerCase().includes(term) ||
          c.refNo.toLowerCase().includes(term)
      );

      if (showAdvanced) {
        if (advancedFilters.state) filtered = filtered.filter((c) => c.state === advancedFilters.state);
        if (advancedFilters.protocol) filtered = filtered.filter((c) => c.protocol === advancedFilters.protocol);
        if (advancedFilters.package) filtered = filtered.filter((c) => c.package === advancedFilters.package);
      }

      if (!term && showAdvanced) {
        filtered = mockSearchResults.filter((c) => {
          const matchState = !advancedFilters.state || c.state === advancedFilters.state;
          const matchProtocol = !advancedFilters.protocol || c.protocol === advancedFilters.protocol;
          const matchPackage = !advancedFilters.package || c.package === advancedFilters.package;
          return matchState && matchProtocol && matchPackage;
        });
      }

      setResults(filtered);
      setIsSearching(false);
    }, 1000);
  };

  const handleClear = () => {
    setSearchTerm("");
    setResults(null);
    setAdvancedFilters({ state: "", protocol: "", package: "", dateFrom: "", dateTo: "" });
    setShowAdvanced(false);
  };

  const handleCopy = (cardNo: string) => {
    navigator.clipboard.writeText(cardNo);
    alert(`Copied: ${cardNo}`);
  };

  const handleView = (card: any) => {
    alert(
      `Card Details:\n\nCard No: ${card.cardNo}\nRef No: ${card.refNo}\nState: ${card.state}\nProtocol: ${card.protocol}\nPackage: ${card.package}\nGenerated By: ${card.generateBy}\nGenerated At: ${card.generateTime}\nExpiry: ${card.expiryDate}\nUsed By: ${card.usedBy || "N/A"}`
    );
  };

  const handleEdit = (card: any) => {
    alert(`Edit card: ${card.cardNo}\n\nIn real app, this would open an edit form.`);
  };

  return (
    <CenteredFormModal
      open={open}
      onClose={onClose}
      title="Card Information"
      hideSubmit
    >
      {/* Search Bar */}
      <div className="space-y-2">
        <div className="flex items-center justify-between">
          <span className="font-semibold text-sm text-signal">
            Card details <span className="text-destructive">*</span>
          </span>
          <button
            type="button"
            onClick={() => setShowAdvanced(!showAdvanced)}
            className={cn(
              "text-xs font-semibold flex items-center gap-1 px-3 py-1 rounded-full border transition-all",
              showAdvanced
                ? "bg-signal text-white border-signal"
                : "text-signal border-signal/30 hover:bg-signal-tint"
            )}
          >
            <SlidersHorizontal className="w-3 h-3" />
            {showAdvanced ? "Hide Advanced" : "Advanced Filters"}
          </button>
        </div>
        <div className="relative">
          <Search className="absolute left-4 top-1/2 -translate-y-1/2 h-4 w-4 text-slate-400" />
          <Input
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            onKeyDown={(e) => e.key === "Enter" && handleSearch()}
            placeholder="Card No / Ref No"
            className="rounded-xl pl-11 border-signal ring-1 ring-signal/30 h-12 text-signal"
          />
        </div>
      </div>

      {/* Advanced Filters */}
      {showAdvanced && (
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 p-5 rounded-2xl bg-slate-50 border border-slate-200 animate-in fade-in slide-in-from-top-2 duration-300">
          <Field label="State">
            <select
              value={advancedFilters.state}
              onChange={(e) => setAdvancedFilters({ ...advancedFilters, state: e.target.value })}
              className="w-full border border-slate-200 rounded-xl px-4 py-2.5 bg-white text-sm text-signal focus:ring-2 focus:ring-signal outline-none"
            >
              <option value="">All States</option>
              <option value="Active">Active</option>
              <option value="Used">Used</option>
              <option value="Expired">Expired</option>
              <option value="Unused">Unused</option>
            </select>
          </Field>

          <Field label="Protocol">
            <select
              value={advancedFilters.protocol}
              onChange={(e) => setAdvancedFilters({ ...advancedFilters, protocol: e.target.value })}
              className="w-full border border-slate-200 rounded-xl px-4 py-2.5 bg-white text-sm text-signal focus:ring-2 focus:ring-signal outline-none"
            >
              <option value="">All Protocols</option>
              <option value="PPPoE">PPPoE</option>
              <option value="Hotspot">Hotspot</option>
              <option value="Static">Static</option>
            </select>
          </Field>

          <Field label="Package">
            <select
              value={advancedFilters.package}
              onChange={(e) => setAdvancedFilters({ ...advancedFilters, package: e.target.value })}
              className="w-full border border-slate-200 rounded-xl px-4 py-2.5 bg-white text-sm text-signal focus:ring-2 focus:ring-signal outline-none"
            >
              <option value="">All Packages</option>
              <option value="1Day-5GB">1Day-5GB</option>
              <option value="7Day-50GB">7Day-50GB</option>
              <option value="30Day-500GB">30Day-500GB</option>
              <option value="1Hour-Unlimited">1Hour-Unlimited</option>
            </select>
          </Field>

          <Field label="Date From">
            <div className="relative">
              <CalendarDays className="absolute right-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400 pointer-events-none" />
              <Input
                type="date"
                value={advancedFilters.dateFrom}
                onChange={(e) => setAdvancedFilters({ ...advancedFilters, dateFrom: e.target.value })}
                className="rounded-xl pr-10 text-signal"
              />
            </div>
          </Field>
        </div>
      )}

      {/* Search Button */}
      <div className="flex gap-3">
        <Button
          onClick={handleSearch}
          disabled={isSearching}
          className="flex-1 rounded-xl font-semibold h-12 bg-signal hover:bg-signal-hover text-white border-0 shadow-md"
        >
          {isSearching ? (
            <>
              <Loader2 className="w-4 h-4 mr-2 animate-spin" /> Searching...
            </>
          ) : (
            <>
              <Search className="w-4 h-4 mr-2" /> Search Card
            </>
          )}
        </Button>
        <Button
          onClick={handleClear}
          variant="outline"
          className="rounded-xl font-semibold h-12 px-6 border-slate-200 text-signal hover:bg-slate-50"
        >
          <RefreshCw className="w-4 h-4" />
        </Button>
      </div>

      {/* Searching */}
      {isSearching && (
        <div className="flex flex-col items-center justify-center py-12 gap-3">
          <Loader2 className="w-10 h-10 text-signal animate-spin" />
          <p className="text-sm text-slate-500">Searching for card...</p>
        </div>
      )}

      {/* Results */}
      {!isSearching && results !== null && results.length > 0 && (
        <div className="space-y-3 animate-in fade-in slide-in-from-bottom-4 duration-300">
          <div className="flex items-center justify-between">
            <p className="text-sm font-semibold text-signal">
              Found <span className="text-signal">{results.length}</span> card(s)
            </p>
          </div>

          {results.map((card) => (
            <div
              key={card.id}
              className="bg-signal-tint rounded-2xl border border-signal/30 p-5 transition-all hover:shadow-md"
            >
              {/* Header */}
              <div className="flex items-start justify-between mb-4">
                <div className="flex items-center gap-3">
                  <div className="w-11 h-11 rounded-xl bg-signal text-white flex items-center justify-center shadow-md">
                    <CreditCard className="w-5 h-5" />
                  </div>
                  <div>
                    <p className="font-mono font-bold text-signal">{card.cardNo}</p>
                    <p className="text-xs text-slate-500 font-mono">{card.refNo}</p>
                  </div>
                </div>
                <span className={cn(
                  "inline-flex items-center px-3 py-1 rounded-full text-xs font-semibold border",
                  getStateBadge(card.state)
                )}>
                  {card.state}
                </span>
              </div>

              {/* Details Grid */}
              <div className="grid grid-cols-2 gap-3 text-xs">
                <div>
                  <p className="text-slate-500 font-semibold uppercase text-[10px] mb-1">Protocol</p>
                  <p className="font-semibold text-signal">{card.protocol}</p>
                </div>
                <div>
                  <p className="text-slate-500 font-semibold uppercase text-[10px] mb-1">Package</p>
                  <p className="font-semibold text-signal">{card.package}</p>
                </div>
                <div>
                  <p className="text-slate-500 font-semibold uppercase text-[10px] mb-1">Generate By</p>
                  <p className="font-semibold flex items-center gap-1 text-signal">
                    <UserCheck className="w-3 h-3" /> {card.generateBy}
                  </p>
                </div>
                <div>
                  <p className="text-slate-500 font-semibold uppercase text-[10px] mb-1">Generate Time</p>
                  <p className="font-semibold flex items-center gap-1 text-signal">
                    <Clock className="w-3 h-3" /> {card.generateTime}
                  </p>
                </div>
                {card.usedBy && (
                  <div className="col-span-2">
                    <p className="text-slate-500 font-semibold uppercase text-[10px] mb-1">Used By</p>
                    <p className="font-semibold text-signal">{card.usedBy}</p>
                  </div>
                )}
              </div>

              {/* Actions */}
              <div className="flex items-center gap-2 mt-4 pt-4 border-t border-signal/20">
                <button
                  onClick={() => handleView(card)}
                  className="flex-1 flex items-center justify-center gap-1.5 py-2 rounded-lg bg-white border border-slate-200 hover:bg-slate-50 transition-colors text-xs font-semibold text-signal"
                >
                  <Eye className="w-3.5 h-3.5" /> View
                </button>
                <button
                  onClick={() => handleCopy(card.cardNo)}
                  className="flex-1 flex items-center justify-center gap-1.5 py-2 rounded-lg bg-white border border-slate-200 hover:bg-slate-50 transition-colors text-xs font-semibold text-signal"
                >
                  <Copy className="w-3.5 h-3.5" /> Copy
                </button>
                <button
                  onClick={() => handleEdit(card)}
                  className="flex-1 flex items-center justify-center gap-1.5 py-2 rounded-lg bg-signal text-white hover:bg-signal-hover transition-colors text-xs font-semibold"
                >
                  <Edit className="w-3.5 h-3.5" /> Edit
                </button>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* No Results */}
      {!isSearching && results !== null && results.length === 0 && (
        <div className="flex flex-col items-center justify-center py-12 gap-4 animate-in fade-in duration-300">
          <div className="w-20 h-20 rounded-full bg-destructive/10 flex items-center justify-center">
            <XCircle className="w-10 h-10 text-destructive" />
          </div>
          <div className="text-center">
            <p className="font-semibold text-signal">No Card Found</p>
            <p className="text-xs text-slate-500 mt-1">
              Try different keywords or adjust your filters
            </p>
          </div>
          <Button
            onClick={handleClear}
            variant="outline"
            className="rounded-full text-xs font-semibold border-slate-200 text-signal"
          >
            <RefreshCw className="w-3.5 h-3.5 mr-1.5" /> Clear Search
          </Button>
        </div>
      )}

      {/* Empty State */}
      {!isSearching && results === null && (
        <div className="flex flex-col items-center justify-center py-12 gap-4 animate-in fade-in duration-300">
          <div className="w-20 h-20 rounded-full bg-signal-tint flex items-center justify-center">
            <FolderSearch className="w-10 h-10 text-signal" />
          </div>
          <div className="text-center">
            <p className="font-semibold text-signal">Search for a Card</p>
            <p className="text-xs text-slate-500 mt-1 max-w-xs">
              Enter a Card Number or Reference Number to view card details. Or use Advanced Filters.
            </p>
          </div>
        </div>
      )}
    </CenteredFormModal>
  );
}