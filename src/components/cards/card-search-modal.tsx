"use client";

import { useState } from "react";
import { CenteredFormModal } from "@/components/cards/centered-form-modal";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import {
  Search, Loader2, CreditCard, CheckCircle2, XCircle, Clock,
  UserCheck, RefreshCw, Copy, Eye, Edit, SlidersHorizontal,
  CalendarDays, AlertCircle, FolderSearch
} from "lucide-react";
import { cn } from "@/lib/utils";

interface CardSearchModalProps {
  open: boolean;
  onClose: () => void;
  onSubmit?: () => void;
}

